/**
 * ID veya doğrudan URL rotasıyla (href) yardım kaydını bulur.
 */
export function getPageHelp(idOrHref: string): PageHelpItem | undefined {
  if (!idOrHref) return undefined;
  
  // Önce doğrudan href eşleşmesi ara
  const cleanHref = idOrHref.split('?')[0].replace(/\/$/, '') || '/';
  if (PAGE_HELP_REGISTRY[cleanHref]) {
    return PAGE_HELP_REGISTRY[cleanHref];
  }

  // ID eşleşmesi ara
  for (const item of Object.values(PAGE_HELP_REGISTRY)) {
    if (item.id === idOrHref || (idOrHref === 'gaps' && item.id === 'product-gaps') || (idOrHref === 'product-gaps' && item.id === 'gaps')) return item;
  }

  // Prefix eşleşmesi ara (örn: /products/categories/catalog -> /products/categories)
  for (const [route, item] of Object.entries(PAGE_HELP_REGISTRY)) {
    if (route !== '/dashboard' && cleanHref.startsWith(route)) {
      return item;
    }
  }

  return undefined;
}
